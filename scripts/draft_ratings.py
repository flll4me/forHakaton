"""Ручная оценка черновиков 1–5 (data/processed/draft_rating_sample.jsonl, формируется scripts/evaluate.py).

ВАЖНО: оценки выставил разработчик (Claude), а не администраторы Grand Mobile и не носители
kk/uz. Это внутренняя проверка, а не результат слепой экспертной оценки из задания.
Шкала: 5 — можно отправлять как есть; 4 — корректно, нейтрально, по правилам; 3 — корректно,
но неточная/неполная (нет нужного пункта, неверный ник); 2 — неверный тип ответа (ошибка
категории ведёт к неподходящему тексту); 1 — недопустимо (обещание, выдуманный пункт, чужой язык).
Раунд 2 (2026-10-30 19:35): модель A после улучшения complaint.admin, генератор после аудита
безопасности. Выборка пересоздана scripts/evaluate.py (отдельный random.Random(7), не зависит от
результатов на test): 15 ru, все 8 kk (больше в valid нет), 15 uz по языку черновика.
Раунд 1 (16:48, другая выборка): 3.53 (ru 3.73, kk 3.12, uz 3.53) — оценки не переносятся.
Внимание: в 17:15 отчёт был ошибочно пересчитан со старыми оценками раунда 1 поверх пересозданной
выборки; раунд 2 это устраняет (см. reports/quality_audit.md).

Запуск: python scripts/draft_ratings.py → reports/draft_quality.md
"""
from __future__ import annotations

import collections
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

RATINGS = [4, 4, 4, 3, 4, 3, 4, 4, 2, 3, 4, 2, 3, 4, 4,      # ru 0-14
           1, 3, 4, 2, 4, 3, 3, 3,                            # kk 15-22
           3, 4, 3, 4, 2, 4, 4, 2, 4, 4, 4, 3, 4, 4, 4]       # uz 23-37
NOTES = {
    3: "игрок уже пробовал эвакуатор — автоответ про кнопку эвакуатора неточен",
    5: "просьба пересмотреть жалобу на игрока: запрос скриншота выдачи наказания не к месту",
    8: "по сути обжалование бана (категория other) — ответ как на жалобу на игрока",
    9: "«фарм репортов»: запрос скриншота выдачи наказания не к месту",
    11: "по сути обжалование (ответ админа «наказание выдано верно») — ответ как на жалобу на игрока",
    12: "заявлен пункт «1.2гз» — в черновике нет GZ 1.2",
    15: "русский текст с одной буквой «һ» определён как kk — черновик на казахском и нерелевантный 5.4",
    16: "18+ контент — без пункта правил",
    18: "жалоба на игрока распознана как жалоба на администратора",
    20: "повтор того же обращения (дубликат в valid) — без пункта правил",
    21: "«7 күнге бан» — 2.1 процитирован без признаков оскорбления в тексте",
    22: "NonRP-арест — без пункта правил",
    23: "NonRP-арест описан как DM",
    25: "жалоба на сотрудников полиции — без пункта правил",
    27: "обжалование бана по FW 1.1 распознано как complaint.other",
    30: "недовольство мягкостью наказания (к админу) — ответ как на оскорбление",
    34: "убийство и оскорбление — админ применил 2.1, черновик только про DM",
}


def main() -> None:
    sample = [json.loads(l) for l in (ROOT / "data/processed/draft_rating_sample.jsonl").read_text(encoding="utf-8").splitlines()]
    assert len(sample) == len(RATINGS), (len(sample), len(RATINGS))
    by_lang = collections.defaultdict(list)
    for s, r in zip(sample, RATINGS):
        by_lang[s["lang"]].append(r)
    lines = ["# Ручная оценка черновиков (1–5)\n",
             "Оценщик — разработчик (Claude), не администраторы Grand Mobile и не носители kk/uz. "
             "Внутренняя проверка, не результат экспертной оценки.\n",
             "| язык | n | средняя | доля ≥4 | доля ≤2 |", "|---|---|---|---|---|"]
    for lang in ("ru", "kk", "uz"):
        v = by_lang[lang]
        lines.append(f"| {lang} | {len(v)} | {statistics.mean(v):.2f} | {sum(x >= 4 for x in v) / len(v):.0%} | {sum(x <= 2 for x in v) / len(v):.0%} |")
    allv = RATINGS
    lines.append(f"| все | {len(allv)} | {statistics.mean(allv):.2f} | {sum(x >= 4 for x in allv) / len(allv):.0%} | {sum(x <= 2 for x in allv) / len(allv):.0%} |")
    ones = [i for i, r in enumerate(RATINGS) if r == 1]
    lines += ["", f"Оценок 1 (запрещённое обещание, выдуманный пункт, чужой язык): {len(ones)}"
              + (" — все из-за языка черновика; обещаний и выдуманных пунктов нет." if ones else "."), "",
              "Раунд 1 (другая случайная выборка, генератор до правок 16:48): ru 3.73, kk 3.12, uz 3.53, все 3.53. "
              "Выборки разные и малые (n=8–15 на язык), разница в пределах шума.", "",
              "Основные причины снижения оценки:", ""]
    lines += [f"- {s['lang']}, {s['category']}: {NOTES[i]}" for i, s in enumerate(sample) if i in NOTES]
    lines += ["", "Ограничение по сути: черновики — подтверждение приёма с правилом и следующим шагом, без вердикта "
              "(вердикт выносит админ). В слепом сравнении с реальными ответами админов, где вердикт уже есть, они "
              "будут проигрывать по полноте; это осознанный выбор ради запрета обещаний наказания."]
    (ROOT / "reports" / "draft_quality.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:9]))


if __name__ == "__main__":
    main()
